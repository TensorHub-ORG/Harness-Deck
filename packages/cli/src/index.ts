function loadDotEnv(envPath = ".env"): void {
  const abs = path.resolve(envPath);
  if (!fs.existsSync(abs)) return;
  const lines = fs.readFileSync(abs, "utf8").split(/\r?\n/);
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const k = trimmed.slice(0, eq).trim();
    const v = trimmed.slice(eq + 1).trim();
    if (!(k in process.env) || process.env[k] === "") {
      process.env[k] = v;
    }
  }
}

function parseFlags(argv: string[]): { positionals: string[]; flags: Record<string, string | boolean> } {
  const positionals: string[] = [];
  const flags: Record<string, string | boolean> = {};
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i]!;
    if (token.startsWith("--")) {
      const key = token.slice(2);
      const next = argv[i + 1];
      if (next && !next.startsWith("--")) {
        flags[key] = next;
        i += 1;
      } else {
        flags[key] = true;
      }
    } else {
      positionals.push(token);
    }
  }
  return { positionals, flags };
}

function strFlag(flags: Record<string, string | boolean>, key: string, fallback?: string): string | undefined {
  const val = flags[key];
  return typeof val === "string" ? val : fallback;
}

async function cmdScan(flags: Record<string, string | boolean>): Promise<void> {
  const report = detectLocalEnvironment();
  if (flags.json) {
    console.log(JSON.stringify(report, null, 2));
    return;
  }
  console.log(`\n=== Harness-Deck Environment Scan (${report.platform}/${report.arch}) ===`);
  console.log(`Host: ${report.hostname} | Node: ${report.node_version}`);
  console.log("\nRuntime Tools:");
  for (const t of report.runtime_tools) {
    const info = t.installed ? (t.version ?? t.path ?? "installed") : "(not installed)";
    console.log(`  [${t.installed ? "OK" : "--"}] ${t.name.padEnd(8)} ${info}`);
  }
  console.log("\nDesktop Agent CLIs (T2 Engineers):");
  for (const c of report.agent_clis) {
    const info = c.installed ? (c.version ?? c.path ?? "installed") : "(not detected)";
    console.log(`  [${c.installed ? "OK" : "--"}] ${c.name.padEnd(8)} (${c.driver}) ${info}`);
  }
  console.log("");
}

async function cmdInit(flags: Record<string, string | boolean>): Promise<void> {
  const repoRoot = process.cwd();
  const deckDir = path.resolve(repoRoot, ".deck");
  fs.mkdirSync(deckDir, { recursive: true });
  fs.mkdirSync(path.join(deckDir, "mcp-clients"), { recursive: true });

  const mode = strFlag(flags, "mode", "local") === "remote" ? "remote" : "local";
  const scope = strFlag(flags, "scope", "o1_only") === "o1_and_k1" ? "o1_and_k1" : "o1_only";
  const endpoint =
    mode === "remote"
      ? strFlag(flags, "relay-url", "http://127.0.0.1:8787")!
      : `file://${path.join(deckDir, "mailroom").replace(/\\/g, "/")}`;

  const bossQq = strFlag(flags, "boss-qq", "")!;
  const groups = strFlag(flags, "groups", "")!;

  const tokens = {
    boss: generateScopedToken(),
    o1: generateScopedToken(),
    k1: generateScopedToken(),
    dispatcher: generateScopedToken(),
    engineer: generateScopedToken(),
    admin: generateScopedToken(),
    napcatO1: generateScopedToken().slice(0, 24),
    napcatK1: generateScopedToken().slice(0, 24),
  };

  // 1. Write .env (unless exists and not --force)
  const envPath = path.join(repoRoot, ".env");
  if (!fs.existsSync(envPath) || flags.force) {
    const envBody = [
      "# Generated by `deck init` — NEVER commit this file!",
      `DECK_ENDPOINT=${endpoint}`,
      `DECK_TOKEN_BOSS=${tokens.boss}`,
      `DECK_TOKEN_KUMI_O1=${tokens.o1}`,
      `DECK_TOKEN_KUMI_K1=${tokens.k1}`,
      `DECK_TOKEN_DISPATCHER=${tokens.dispatcher}`,
      `DECK_TOKEN_ENGINEER=${tokens.engineer}`,
      `DECK_RELAY_HOST=0.0.0.0`,
      `DECK_RELAY_PORT=8787`,
      `DECK_RELAY_ADMIN_TOKEN=${tokens.admin}`,
      `DECK_BOSS_QQ_LIST=${bossQq}`,
      `DECK_COMMUNITY_GROUP_LIST=${groups}`,
      `NAPCAT_O1_WS_URL=ws://127.0.0.1:3001`,
      `NAPCAT_O1_TOKEN=${tokens.napcatO1}`,
      `NAPCAT_O1_WEBUI_PORT=6099`,
      `NAPCAT_K1_WS_URL=ws://127.0.0.1:3002`,
      `NAPCAT_K1_TOKEN=${tokens.napcatK1}`,
      `NAPCAT_K1_WEBUI_PORT=6100`,
      `DECK_WORKSTATION_CONFIG=.deck/workstation.yaml`,
      `DECK_AUDIT_DIR=.deck/audit`,
      `DECK_ARTIFACT_TTL_HOURS=168`,
      "",
    ].join("\n");
    fs.writeFileSync(envPath, envBody, "utf8");
  }

  // 2. Auto-detect local CLIs and create .deck/workstation.yaml
  const envReport = detectLocalEnvironment();
  const engineers: WorkstationConfig["engineers"] = {
    mock: {
      driver: "mock-cli",
      enabled: true,
      strengths: ["doctor", "smoke-test"],
      default_timeout_min: 5,
    },
  };
  for (const cli of envReport.agent_clis) {
    if (cli.driver) {
      engineers[cli.name] = {
        driver: cli.driver,
        enabled: cli.installed,
        binary: cli.path,
        strengths: [cli.name],
        default_timeout_min: 20,
      };
    }
  }

  const workstation: WorkstationConfig = {
    node_id: os.hostname().toLowerCase().replace(/[^a-z0-9-]/g, "-") || "local-pc",
    platform: envReport.platform,
    max_concurrent_tasks: 2,
    worktree_root: path.join(deckDir, "worktrees"),
    workspaces: {
      "harness-deck": {
        path: repoRoot,
        git_isolation: "worktree",
        default_branch: "main",
      },
    },
    engineers,
  };
  const wsPath = path.join(deckDir, "workstation.yaml");
  fs.writeFileSync(wsPath, YAML.stringify(workstation), "utf8");

  // 3. Register default agents in local Mailroom
  const mailroom = new LocalMailroomClient(path.join(deckDir, "mailroom"));
  try {
    await mailroom.registerAgent({ agent_id: "boss", role: "boss", tier: "T0", token: tokens.boss });
    await mailroom.registerAgent({
      agent_id: "kumi-o1",
      role: "secretary",
      tier: "T1",
      reports_to: "boss",
      display_name: "库米 O1 (秘书主管)",
      token: tokens.o1,
    });
    await mailroom.registerAgent({
      agent_id: `dispatcher-${workstation.node_id}`,
      role: "worker",
      tier: "T2",
      reports_to: "kumi-o1",
      display_name: `Desktop Foreman (${workstation.node_id})`,
      token: tokens.dispatcher,
    });
    await mailroom.registerAgent({
      agent_id: "desktop-engineer",
      role: "worker",
      tier: "T2",
      reports_to: "kumi-o1",
      display_name: "Interactive Desktop Agent",
      token: tokens.engineer,
    });
    if (scope === "o1_and_k1") {
      await mailroom.registerAgent({
        agent_id: "kumi-k1",
        role: "frontline",
        tier: "T3",
        reports_to: "kumi-o1",
        display_name: "库米 K1 (社区专员)",
        token: tokens.k1,
      });
    }
  } finally {
    mailroom.close();
  }

  // 4. Generate ready-to-use MCP client config files for desktop, O1, and K1
  const desktopMcp = {
    mcpServers: generateMcpServersMap({
      repoRoot,
      endpoint,
      agentId: "desktop-engineer",
      role: "worker",
      tier: "T2",
      token: tokens.engineer,
      includeDispatch: true,
      includeKb: true,
    }),
  };
  fs.writeFileSync(path.join(deckDir, "mcp-clients", "desktop-agent.mcp.json"), JSON.stringify(desktopMcp, null, 2));

  const o1Mcp = {
    mcpServers: generateMcpServersMap({
      repoRoot,
      endpoint,
      agentId: "kumi-o1",
      role: "secretary",
      tier: "T1",
      token: tokens.o1,
      includeQq: true,
      includeKb: true,
    }),
  };
  fs.writeFileSync(path.join(deckDir, "mcp-clients", "kumi-o1.mcp.json"), JSON.stringify(o1Mcp, null, 2));

  if (scope === "o1_and_k1") {
    const k1Mcp = {
      mcpServers: generateMcpServersMap({
        repoRoot,
        endpoint,
        agentId: "kumi-k1",
        role: "frontline",
        tier: "T3",
        token: tokens.k1,
        includeQq: true,
        includeKb: true,
      }),
    };
    fs.writeFileSync(path.join(deckDir, "mcp-clients", "kumi-k1.mcp.json"), JSON.stringify(k1Mcp, null, 2));
  }

  // 5. Persist onboarding install-state.json
  const state = InstallStateSchema.parse({
    version: "1.0",
    updated_at: new Date().toISOString(),
    completed_steps: ["scan", "init"],
    deployment_scope: scope,
    qq_deploy_target: mode === "remote" ? "remote_ssh" : "local",
    boss_qq_list: bossQq ? bossQq.split(",").filter(Boolean) : [],
    community_group_list: groups ? groups.split(",").filter(Boolean) : [],
    selected_engineers: Object.entries(engineers)
      .filter(([, e]) => e.enabled)
      .map(([n]) => n),
    allowlisted_workspaces: { "harness-deck": repoRoot },
    l3_require_approval: true,
  });
  fs.writeFileSync(path.join(deckDir, "install-state.json"), JSON.stringify(state, null, 2));

  console.log("Harness-Deck initialized successfully!");
  console.log(`  - Env file:         ${envPath}`);
  console.log(`  - Workstation cfg:  ${wsPath}`);
  console.log(`  - MCP configs dir:  ${path.join(deckDir, "mcp-clients")}`);
  console.log(`  - Endpoint:         ${endpoint}`);
  console.log("\nNext step: run `pnpm deck doctor` to verify end-to-end protocol & security checks.");
}

async function cmdRelay(flags: Record<string, string | boolean>): Promise<void> {
  loadDotEnv();
  const host = strFlag(flags, "host", process.env.DECK_RELAY_HOST ?? "0.0.0.0")!;
  const port = Number(strFlag(flags, "port", process.env.DECK_RELAY_PORT ?? "8787"));
  const dataDir = strFlag(flags, "data-dir", ".deck/mailroom")!;
  const adminToken = strFlag(flags, "admin-token", process.env.DECK_RELAY_ADMIN_TOKEN);

  const server = new DeckRelayServer({ host, port, dataDir, adminToken });

  // Auto-seed scoped agent tokens from environment variables so fresh VPS relay boots ready-to-auth
  const seedList: Array<{
    agent_id: string;
    role: AgentRole;
    tier: "T0" | "T1" | "T2" | "T3";
    reports_to: string | null;
    display_name: string;
    token?: string;
  }> = [
    { agent_id: "boss", role: "boss", tier: "T0", reports_to: null, display_name: "老板 (T0)", token: process.env.DECK_TOKEN_BOSS },
    { agent_id: "kumi-o1", role: "secretary", tier: "T1", reports_to: "boss", display_name: "库米 O1 (秘书主管)", token: process.env.DECK_TOKEN_KUMI_O1 },
    { agent_id: "kumi-k1", role: "frontline", tier: "T3", reports_to: "kumi-o1", display_name: "库米 K1 (社区专员)", token: process.env.DECK_TOKEN_KUMI_K1 },
    {
      agent_id: process.env.DECK_DISPATCHER_AGENT_ID ?? "dispatcher-desktop",
      role: "worker",
      tier: "T2",
      reports_to: "kumi-o1",
      display_name: "Desktop Foreman",
      token: process.env.DECK_TOKEN_DISPATCHER,
    },
    {
      agent_id: "desktop-engineer",
      role: "worker",
      tier: "T2",
      reports_to: "kumi-o1",
      display_name: "Interactive Desktop Agent",
      token: process.env.DECK_TOKEN_ENGINEER,
    },
  ];
  for (const s of seedList) {
    if (s.token) {
      server.store.registerAgent({
        agent_id: s.agent_id,
        role: s.role,
        tier: s.tier,
        reports_to: s.reports_to,
        display_name: s.display_name,
        token: s.token,
      });
    }
  }

  const bound = await server.start();
  console.log(`[deck-relay] Listening on http://${bound.host}:${bound.port} (WS: /ws, dataDir: ${path.resolve(dataDir)})`);

  process.on("SIGINT", () => {
    void server.stop().then(() => process.exit(0));
  });
}

async function cmdDispatch(flags: Record<string, string | boolean>): Promise<void> {
  loadDotEnv();
  const configPath = strFlag(flags, "config", process.env.DECK_WORKSTATION_CONFIG ?? ".deck/workstation.yaml")!;
  const workstation = loadWorkstationConfig(configPath);
  const client = createMailroomClient(
    strFlag(flags, "endpoint", process.env.DECK_ENDPOINT),
    strFlag(flags, "token", process.env.DECK_TOKEN_DISPATCHER ?? process.env.DECK_AGENT_TOKEN)
  );
  const dispatcher = new DeckDispatcher({
    client,
    workstation,
    agentId: process.env.DECK_DISPATCHER_AGENT_ID,
  });
  await dispatcher.start();

  process.on("SIGINT", () => {
    dispatcher.stop();
    client.close();
    process.exit(0);
  });
}

async function cmdQqBridge(flags: Record<string, string | boolean>): Promise<void> {
  loadDotEnv();
  const profile = strFlag(flags, "profile", "o1") === "k1" ? "k1" : "o1";
  const agentId = strFlag(flags, "agent-id", profile === "o1" ? "kumi-o1" : "kumi-k1")!;
  const token =
    strFlag(flags, "token") ?? (profile === "o1" ? process.env.DECK_TOKEN_KUMI_O1 : process.env.DECK_TOKEN_KUMI_K1);
  const napcatWsUrl =
    strFlag(flags, "napcat-ws") ??
    (profile === "o1" ? process.env.NAPCAT_O1_WS_URL : process.env.NAPCAT_K1_WS_URL) ??
    (profile === "o1" ? "ws://127.0.0.1:3001" : "ws://127.0.0.1:3002");
  const napcatToken =
    strFlag(flags, "napcat-token") ?? (profile === "o1" ? process.env.NAPCAT_O1_TOKEN : process.env.NAPCAT_K1_TOKEN);

  const client = createMailroomClient(strFlag(flags, "endpoint", process.env.DECK_ENDPOINT), token);
  const bossClient =
    profile === "o1" && process.env.DECK_TOKEN_BOSS
      ? createMailroomClient(strFlag(flags, "endpoint", process.env.DECK_ENDPOINT), process.env.DECK_TOKEN_BOSS)
      : undefined;
  const defaultRisk = process.env.DECK_DEFAULT_RISK_LEVEL;
  const llm =
    process.env.DECK_QQ_LLM_BASE_URL && process.env.DECK_QQ_LLM_API_KEY && process.env.DECK_QQ_LLM_MODEL
      ? {
          baseUrl: process.env.DECK_QQ_LLM_BASE_URL,
          apiKey: process.env.DECK_QQ_LLM_API_KEY,
          model: process.env.DECK_QQ_LLM_MODEL,
        }
      : undefined;
  const daemon = new QqBridgeDaemon({
    profile,
    agentId,
    mailroom: client,
    bossMailroom: bossClient,
    napcatWsUrl,
    napcatToken,
    bossQqList: (process.env.DECK_BOSS_QQ_LIST ?? "").split(",").map((s) => s.trim()).filter(Boolean),
    communityGroupList: (process.env.DECK_COMMUNITY_GROUP_LIST ?? "").split(",").map((s) => s.trim()).filter(Boolean),
    defaultRiskLevel: defaultRisk === "L1" || defaultRisk === "L3" ? defaultRisk : "L2",
    defaultWorkerId: process.env.DECK_DISPATCHER_AGENT_ID,
    qmmiWebhookUrl: profile === "o1" ? process.env.QMMI_O1_API_URL : process.env.QMMI_K1_API_URL,
    llm,
    personaFile: process.env.DECK_QQ_PERSONA_FILE,
  });
  await daemon.start();

  process.on("SIGINT", () => {
    daemon.stop();
    client.close();
    process.exit(0);
  });
}

async function cmdDeploySsh(flags: Record<string, string | boolean>): Promise<void> {
  loadDotEnv();
  const host = strFlag(flags, "host");
  const user = strFlag(flags, "user");
  if (!host || !user) {
    console.error("Usage: deck deploy-ssh --host <ip-or-domain> --user <ssh-user> [--port 22] [--key ~/.ssh/id_ed25519] [--remote-dir /opt/harness-deck] [--scope o1_only|o1_and_k1] [--dry-run]");
    process.exit(1);
  }
  const runtimeFlag = strFlag(flags, "runtime", "auto");
  const result = runRemoteSshDeploy({
    host,
    user,
    port: Number(strFlag(flags, "port", "22")),
    keyPath: strFlag(flags, "key"),
    remoteDir: strFlag(flags, "remote-dir", "/opt/harness-deck")!,
    scope: strFlag(flags, "scope", "o1_only") === "o1_and_k1" ? "o1_and_k1" : "o1_only",
    relayPort: Number(strFlag(flags, "relay-port", process.env.DECK_RELAY_PORT ?? "8787")),
    envFilePath: path.resolve(strFlag(flags, "env", ".env")!),
    repoRoot: process.cwd(),
    runtime: runtimeFlag === "docker" || runtimeFlag === "native" ? runtimeFlag : "auto",
    withQqBridge: Boolean(flags["with-qq-bridge"]),
    dryRun: Boolean(flags["dry-run"]),
  });
  console.log(JSON.stringify(result, null, 2));
}

async function cmdDoctor(): Promise<void> {
  loadDotEnv();
  const checks: Array<{ name: string; pass: boolean; detail: string }> = [];

  // 1. Environment check
  const env = detectLocalEnvironment();
  const detectedClis = env.agent_clis.filter((c) => c.installed).map((c) => c.name);
  checks.push({
    name: "Runtime Environment",
    pass: true,
    detail: `Node ${env.node_version} on ${env.platform}, CLIs detected: ${detectedClis.join(", ") || "none (mock-cli available)"}`,
  });

  // 2. Hard RBAC self-test: T3 -> T0 & T3 -> T2 must fail
  const t3ToT0 = validateRouting({ type: "report.digest", fromTier: "T3", toTier: "T0" });
  const t3ToT2 = validateRouting({ type: "task.dispatch", fromTier: "T3", toTier: "T2" });
  const l3NoApproval = validateRouting({ type: "task.dispatch", fromTier: "T1", toTier: "T2", riskLevel: "L3" });
  checks.push({
    name: "Hard RBAC & L3 Approval Gate (T0>T1>T2>T3)",
    pass: !t3ToT0.allowed && !t3ToT2.allowed && !l3NoApproval.allowed,
    detail: "T3->T0 blocked, T3->T2 isolated, L3 without T0 approval blocked",
  });

  // 3. Secret scrubber self-test
  const fakeKey = ["sk", "proj", "1234567890abcdefghijklmnop"].join("-");
  const scrubbed = scrubSecrets(`API_KEY=${fakeKey}`);
  checks.push({
    name: "Secret Scrubber Redaction",
    pass: !scrubbed.includes("1234567890abcdef") && scrubbed.includes("[REDACTED"),
    detail: scrubbed,
  });

  // 4. End-to-end Mailroom + Dispatcher (mock-cli) roundtrip in isolated temp dir
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "hdeck-doctor-"));
  const demoRepo = path.join(tmpDir, "repo");
  fs.mkdirSync(demoRepo, { recursive: true });
  const client = new LocalMailroomClient(path.join(tmpDir, "mailroom"));
  const dispatcher = new DeckDispatcher({
    client,
    agentId: "dispatcher-doctor",
    secretaryId: "kumi-o1",
    workstation: {
      node_id: "doctor",
      platform: env.platform,
      max_concurrent_tasks: 1,
      worktree_root: path.join(tmpDir, "wt"),
      workspaces: { demo: { path: demoRepo, git_isolation: "none", default_branch: "main" } },
      engineers: { mock: { driver: "mock-cli", enabled: true, strengths: ["doctor"], default_timeout_min: 1 } },
    },
    logger: () => {},
  });

  try {
    await dispatcher.registerWorkstation();
    const sent = await client.sendEnvelope({
      from: { agent_id: "kumi-o1", role: "secretary", tier: "T1" },
      to: { agent_id: "dispatcher-doctor", role: "worker", tier: "T2" },
      type: "task.dispatch",
      payload: {
        task_id: "T-DOC",
        project: "demo",
        title: "Doctor E2E Roundtrip",
        instruction: "Verify O1 -> Mailroom -> Dispatcher -> O1",
        preferred_driver: "mock",
        sandbox_profile: "L1_READONLY",
      },
    });
    await dispatcher.pollOnce();
    const o1Inbox = await client.pullInbox("kumi-o1");
    const result = o1Inbox.find((e) => e.type === "task.result" && e.trace_id === sent.trace_id);
    checks.push({
      name: "E2E Dispatch Roundtrip (O1 <-> Mailroom <-> Worker)",
      pass: Boolean(result && result.payload.status === "success"),
      detail: result ? `Received task.result with ${result.attachments.length} artifact(s), trace=${sent.trace_id}` : "No result received",
    });
  } finally {
    dispatcher.stop();
    client.close();
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }

  console.log("\n=== Harness-Deck Doctor Report ===");
  let allPass = true;
  for (const c of checks) {
    if (!c.pass) allPass = false;
    console.log(`  [${c.pass ? "PASS" : "FAIL"}] ${c.name}`);
    console.log(`         ${c.detail}`);
  }
  console.log("");
  if (!allPass) process.exit(1);
}

async function cmdTrace(traceId: string | undefined): Promise<void> {
  loadDotEnv();
  if (!traceId) {
    console.error("Usage: deck trace <trace_id>");
    process.exit(1);
  }
  const client = createMailroomClient(process.env.DECK_ENDPOINT, process.env.DECK_TOKEN_BOSS ?? process.env.DECK_TOKEN_KUMI_O1);
  try {
    const envelopes = await client.getTrace(traceId);
    console.log(`\n=== Trace ${traceId} (${envelopes.length} envelopes) ===`);
    for (const env of envelopes) {
      console.log(
        `[${env.timestamp}] ${env.from.agent_id}(${env.from.tier}) -> ${env.to.agent_id}(${env.to.tier}) | ${env.type} | id=${env.id}`
      );
      console.log(`  payload: ${JSON.stringify(env.payload).slice(0, 300)}`);
    }
  } finally {
    client.close();
  }
}

