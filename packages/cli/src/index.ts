async function cmdApproval(decision: "approved" | "rejected", code: string | undefined, comment?: string): Promise<void> {
  loadDotEnv();
  if (!code) {
    console.error(`Usage: deck ${decision === "approved" ? "approve" : "reject"} <short_code_or_id> [comment]`);
    process.exit(1);
  }
  const client = createMailroomClient(process.env.DECK_ENDPOINT, process.env.DECK_TOKEN_BOSS);
  try {
    const rec = await client.decideApproval({
      idOrShortCode: code,
      decision,
      decided_by: "boss-cli",
      comment,
    });
    console.log(JSON.stringify(rec, null, 2));
  } finally {
    client.close();
  }
}

async function cmdMcpConfig(flags: Record<string, string | boolean>): Promise<void> {
  loadDotEnv();
  const role: AgentRole = AgentRoleSchema.parse(strFlag(flags, "role", "worker"));
  const tier = ROLE_TO_TIER[role];
  const agentId = strFlag(flags, "agent-id", role === "secretary" ? "kumi-o1" : role === "frontline" ? "kumi-k1" : "desktop-engineer")!;
  const mcpServers = generateMcpServersMap({
    repoRoot: process.cwd(),
    endpoint: strFlag(flags, "endpoint", process.env.DECK_ENDPOINT ?? "file://./.deck/mailroom")!,
    agentId,
    role,
    tier,
    token: strFlag(flags, "token", process.env.DECK_TOKEN_ENGINEER ?? "")!,
    includeDispatch: role === "worker" || role === "boss",
    includeQq: role === "secretary" || role === "frontline",
    includeKb: true,
  });
  console.log(JSON.stringify({ mcpServers }, null, 2));
}

